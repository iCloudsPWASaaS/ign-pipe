  coalesce(sum(qd.unit_price), 0) as unit_price,
  coalesce(sum(qd.quantity * qd.unit_price), 0) as cost,
  coalesce(sum(qd.quantity * qd.unit_price) * 0.2, 0) as vat,
  coalesce(sum(qd.quantity * qd.unit_price) * 1.2, 0) as total
from pipe.quote q
left join pipe.property p on p.p_id = q.p_id
left join pipe.quote_detail qd on qd.quote_no = q.quote_no
group by q.quote_no, q.quote_date, q.quote_info, q.p_id, p.p_name, p.p_no, p.p_location, q.issue_no, q.reported_issue_no, q.r_id, q.s_id
order by q.quote_date desc;

create or replace view pipe.scheduler_view as
select s.*, p.r_id, p.p_name, p.p_no, p.p_location, p.post_code, c.contractor
from pipe.schedule s
left join pipe.property p on p.p_id = s.p_id
left join pipe.contractor c on c.c_id = s.c_id;

create or replace view pipe.timesheet_view as
select
  t.*,
  c.contractor,
  p.p_name,
  p.p_no,
  p.p_location,
  round(extract(epoch from (t.end_time - t.start_time)) / 60.0, 0) as total_minutes,
  round(extract(epoch from (t.end_time - t.start_time)) / 60.0 * 0.3, 2) as labour
from pipe.timesheet t
left join pipe.contractor c on c.c_id = t.c_id
left join pipe.property p on p.p_id = t.p_id;

