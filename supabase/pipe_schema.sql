-- Reset identity sequences after explicit seed ids.
do $$
declare
  r record;
begin
  for r in
    select table_name, column_name
    from information_schema.columns
    where table_schema = 'pipe'
      and is_identity = 'YES'
  loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, %L), coalesce((select max(%I) from pipe.%I), 1), true)',
      'pipe.' || r.table_name, r.column_name, r.column_name, r.table_name
    );
  end loop;
end $$;

