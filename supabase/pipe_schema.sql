-- The legacy MySQL app relied on loose column defaults. Drop NOT NULL from
-- non-primary-key columns so partial legacy-style inserts keep working.
do $$
declare
  r record;
begin
  for r in
    select c.table_name, c.column_name
    from information_schema.columns c
    where c.table_schema = 'pipe'
      and c.is_nullable = 'NO'
      and c.column_default is null
      and c.is_identity = 'NO'
      and not exists (
        select 1
        from information_schema.table_constraints tc
        join information_schema.key_column_usage kcu
          on kcu.constraint_name = tc.constraint_name
         and kcu.table_schema = tc.table_schema
        where tc.table_schema = 'pipe'
          and tc.constraint_type = 'PRIMARY KEY'
          and tc.table_name = c.table_name
          and kcu.column_name = c.column_name
      )
  loop
    execute format('alter table pipe.%I alter column %I drop not null', r.table_name, r.column_name);
  end loop;
end $$;

